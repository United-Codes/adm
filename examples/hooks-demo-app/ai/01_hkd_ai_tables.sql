-- Tables of the "Classify uploads with an LLM" course. They sit next to the hooks demo tables
-- and keep the hkd_ prefix. As there, no foreign key points into ADM: a result is worth keeping
-- after the document it describes is gone.
--
-- Re-runnable: a table that exists is left alone, the seed data is merged.

declare
  procedure ensure_table (
    p_table_name in varchar2
  , p_ddl        in varchar2
  )
  as
    l_exists number;
  begin
    select case when exists (
             select 1
               from user_tables t
              where t.table_name = upper(p_table_name)
           ) then 1 else 0 end
      into l_exists
      from dual;

    if l_exists = 0 then
      execute immediate p_ddl; -- @dblinter ignore(g-9501): p_ddl is one of the literals of this script, never user input
    end if;
  end ensure_table;
begin
  -- The document types the model may answer with, and what happens to a document of that type.
  -- release_mode AUTO puts a valid answer into effect at once. REVIEW holds it for a person.
  ensure_table('HKD_AI_DOC_TYPES', q'[
    create table hkd_ai_doc_types (
      doc_type     varchar2(30 char)   not null
    , description  varchar2(200 char)  not null
    , release_mode varchar2(6 char)    default on null 'AUTO' not null
    , sort_order   number(3)           not null
    , constraint hkd_ai_doc_types_pk primary key (doc_type)
    , constraint hkd_ai_doc_types_mode_ck check (release_mode in ('AUTO', 'REVIEW'))
    , constraint hkd_ai_doc_types_name_ck check (doc_type = lower(doc_type) and instr(doc_type, ' ') = 0)
    )
  ]');

  -- One row for every time the classifier looked at a document. The newest row per document
  -- is the current verdict (hkd_ai_latest_v). The model's free text is kept here and not in an
  -- annotation, because annotations are handed to the chat agent as it browses documents.
  ensure_table('HKD_AI_RESULTS', q'[
    create table hkd_ai_results (
      result_id         number generated by default on null as identity
    , document_id       number              not null
    , version_id        number
    , doc_type          varchar2(100 char)
    , status            varchar2(12 char)   not null
    , reason            varchar2(200 char)
    , model             varchar2(100 char)
    , prompt_tokens     number
    , completion_tokens number
    , created_at        timestamp with local time zone default on null current_timestamp not null
    , reviewed_by       varchar2(255 char)
    , reviewed_at       timestamp with local time zone
    , constraint hkd_ai_results_pk primary key (result_id)
    , constraint hkd_ai_results_status_ck check (status in ('RELEASED', 'NEEDS_REVIEW', 'ACCEPTED', 'REVOKED', 'FAILED'))
    )
  ]');

  -- What a person says each sample file is. The course measures the classifier against it.
  -- 00_load_pdfs.sql fills it. Not used by the classifier itself.
  ensure_table('HKD_AI_LABELS', q'[
    create table hkd_ai_labels (
      file_name     varchar2(255 char) not null
    , expected_type varchar2(30 char)  not null
    , note          varchar2(200 char)
    , constraint hkd_ai_labels_pk primary key (file_name)
    )
  ]');
end;
/

declare
  l_exists number;
  c_ddl    constant varchar2(200 char) := 'create index hkd_ai_results_doc_ix on hkd_ai_results (document_id, result_id)';
begin
  select case when exists (
           select 1
             from user_indexes i
            where i.index_name = 'HKD_AI_RESULTS_DOC_IX'
         ) then 1 else 0 end
    into l_exists
    from dual;

  if l_exists = 0 then
    execute immediate c_ddl;
  end if;
end;
/

-- A folder that carries the annotation ai.skip, and every folder below it, is kept away from the
-- classifier: its files are never sent to the model.
create or replace view hkd_ai_skip_folders_v as
select f.folder_id
     , f.folder_path
  from adm_folders f
  join adm_folder_annotations fa
    on fa.folder_id = f.folder_id
 where fa.annotation_key = 'ai.skip'
   and f.deleted_flag    = 'N'
;

-- The documents the classifier can read and that nothing has queued right now: a PDF or an image,
-- not over 20 MB (the limit of hkd_ai_api), in a folder that is not marked ai.skip, and with no event
-- waiting in the queue. The backfill reads its candidates from here, so a document that is queued
-- already is not queued twice.
create or replace view hkd_ai_candidates_v as
select d.document_id
     , d.latest_version_id
     , d.document_name
     , d.created_date
     , f.folder_path
  from adm_documents d
  join adm_folders f
    on f.folder_id = d.folder_id
  join adm_document_versions v
    on v.version_id = d.latest_version_id
 where d.deleted_flag = 'N'
   and d.file_mime_type in ('application/pdf', 'image/png', 'image/jpeg', 'image/gif', 'image/webp')
   and v.file_size <= 20 * 1024 * 1024
   and not exists (
         select 1
           from hkd_ai_skip_folders_v s
          where f.folder_path = s.folder_path
             or f.folder_path like adm_utils.escape_like(s.folder_path) || '/%' escape '\'
       )
   and not exists (
         select 1
           from aq$hkd_event_qt q
          where q.queue     = 'HKD_EVENT_Q'
            and q.msg_state in ('READY', 'WAIT')
            and q.user_data.document_id = d.document_id
       )
;

comment on table hkd_ai_candidates_v is 'The documents the classifier can read that no queued event covers: PDFs and images up to 20 MB outside folders marked ai.skip.';

comment on table hkd_ai_skip_folders_v is 'Folders whose files the classifier never sends to the model: the folders with the annotation ai.skip. It applies to all folders below them too.';

comment on table hkd_ai_doc_types is 'Document types the classifier may answer with. release_mode AUTO puts a valid answer into effect at once, REVIEW holds it for a person.';
comment on table hkd_ai_results is 'Every classification: the verdict, the model that gave it and the tokens it used. The newest row per document is current.';
comment on column hkd_ai_results.status is 'RELEASED: a valid answer of an AUTO type took effect. NEEDS_REVIEW: waiting for a person. ACCEPTED: a person confirmed it. REVOKED: a person took the release back. FAILED: the model call did not finish.';
comment on column hkd_ai_results.reason is 'The model''s own one-line reason, cut to 200 characters. Text from a document, so treat it as untrusted.';

create or replace view hkd_ai_latest_v as
select r.result_id
     , r.document_id
     , d.document_name
     , r.version_id
     , r.doc_type
     , r.status
     , r.reason
     , r.model
     , r.prompt_tokens
     , r.completion_tokens
     , r.created_at
     , r.reviewed_by
     , r.reviewed_at
  from hkd_ai_results r
  join adm_documents d
    on d.document_id = r.document_id
 where r.result_id = (
         select max(r2.result_id)
           from hkd_ai_results r2
          where r2.document_id = r.document_id
       )
;

comment on table hkd_ai_labels is 'The correct type of each sample file, for measuring the classifier. Filled by 00_load_pdfs.sql.';
comment on table hkd_ai_latest_v is 'The current classifier verdict of every document that has one.';

-- Seed data. merge, so a re-run neither duplicates the types nor resets a description or a
-- release rule that someone changed.
-- A wrong invoice in the books is a small mistake and a wrong contract is not, so contracts and
-- HR letters wait for a person. "other" waits too: the model found no fitting type.
merge into hkd_ai_doc_types t
using (
  select 'invoice' as doc_type, 'A bill from a supplier asking for payment: invoice number, items, amount due' as description, 'AUTO' as release_mode, 10 as sort_order from dual
  union all select 'quote',     'An offer with prices that does not ask for payment yet', 'AUTO', 20 from dual
  union all select 'datasheet', 'Technical data about a product', 'AUTO', 30 from dual
  union all select 'contract',  'An agreement between parties, or an amendment to one, with clauses and signatures', 'REVIEW', 40 from dual
  union all select 'hr',        'A personal letter or record about an employee', 'REVIEW', 50 from dual
  union all select 'other',     'Anything that is none of the types above', 'REVIEW', 90 from dual
) s
on (t.doc_type = s.doc_type)
when matched then
  update set t.sort_order = s.sort_order
when not matched then
  insert (doc_type, description, release_mode, sort_order)
  values (s.doc_type, s.description, s.release_mode, s.sort_order);
