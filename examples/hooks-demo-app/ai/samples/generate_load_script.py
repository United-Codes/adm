#!/usr/bin/env python3
"""Writes ../00_load_pdfs.sql: a script that loads the sample PDFs into ADM without any file access.

Every PDF becomes a base64 literal inside the script, so a reader needs SQLcl and nothing else.
Run it after generate_samples.py:

    python3 generate_load_script.py
"""
import base64
import csv
from pathlib import Path

HERE = Path(__file__).parent
PDFS = HERE / "pdf"
OUT = HERE.parent / "00_load_pdfs.sql"
CHUNK = 1800  # characters per PL/SQL literal; far below the 32 KB literal limit

HEAD = """-- Loads the sample PDFs of the "Classify uploads with an LLM" course into ADM.
-- Run in SQLcl or SQL*Plus, connected as the ADM schema owner. GENERATED by
-- samples/generate_load_script.py: change the PDFs there, not here.
--
--   @00_load_pdfs.sql <file name | ALL> [folder] [NOHOOKS]
--
-- Examples:   @00_load_pdfs.sql inv_ferrotek_1042.pdf       loads one file
--             @00_load_pdfs.sql ALL                         loads the whole set
--             @00_load_pdfs.sql ALL hkd_archive NOHOOKS     loads it into another folder and
--                                                           does not run the upload hook
--
-- The files go into a folder in the home folder of the ADM user named below (default hkd_inbox),
-- as that user. A file that is already there is left alone. Uploading fires the upload hook, so
-- the worker classifies each file moments after this script ends. NOHOOKS skips the hook, the
-- way a file that was uploaded before the hook existed has never seen it.
-- ALL leaves out the second version of the contract: lesson 3 adds it as a new version.
--
-- Every company, person and number in the PDFs is invented.

-- @dblinter ignore(g-5010): a tutorial script prints its results with dbms_output on
-- purpose, so the reader sees them directly in SQLcl.

define hkd_user = ADMIN
define hkd_file = '&1'

set define on
set verify off
set termout off
column 2 new_value 2
column 3 new_value 3
-- @dblinter ignore(g-2180): the quoted names are the column names the optional parameters need
-- @dblinter ignore(g-1040): where 1 = 0 returns no row on purpose: only the column names matter
select null "2", null "3" from dual where 1 = 0;
set termout on
define hkd_folder = '&2'
define hkd_hooks = '&3'
set serveroutput on
set feedback off

declare
  l_folder_id   adm_folders.folder_id%type;
  l_home        adm_folders.folder_id%type;
  l_loaded      pls_integer := 0;
  c_folder_name constant varchar2(100 char) := coalesce('&hkd_folder', 'hkd_inbox');

  procedure put (
    p_name in varchar2
  , p_b64  in clob
  )
  as
    l_exists number;
    l_doc_id adm_documents.document_id%type;
  begin
    select case when exists (
             select 1
               from adm_documents d
              where d.folder_id     = l_folder_id -- @dblinter ignore(g-7130): put is a helper of this one block, and the folder is the state of the block
                and d.document_name = p_name
                and d.deleted_flag  = 'N'
           ) then 1 else 0 end
      into l_exists
      from dual;

    if l_exists = 1 then
      sys.dbms_output.put_line('  already there: ' || p_name);
      return;
    end if;

    l_doc_id := adm_document_api.create_document(
      p_folder_id      => l_folder_id -- @dblinter ignore(g-7130): put is a helper of this one block, and the folder is the state of the block
    , p_document_name  => p_name
    , p_file_content   => apex_web_service.clobbase642blob(p_b64)
    , p_file_mime_type => 'application/pdf'
    , p_run_hooks      => upper('&hkd_hooks') != 'NOHOOKS'
    );
    l_loaded := l_loaded + 1; -- @dblinter ignore(g-7130): put is a helper of this one block, and the counter is the state of the block
    sys.dbms_output.put_line('  loaded: ' || p_name || ' (document ' || l_doc_id || ')');
  end put;
begin
  adm_context_api.system_user_login('&hkd_user');

  l_home := adm_folder_api.get_folder_id('/users/' || lower('&hkd_user'));
  begin
    l_folder_id := adm_folder_api.get_folder_id('/users/' || lower('&hkd_user') || '/' || c_folder_name);
  exception
    when adm_error.e_folder_not_found then
      l_folder_id := adm_folder_api.add_folder(c_folder_name, l_home);
  end;
"""

TAIL = """
  if l_loaded = 0 then
    sys.dbms_output.put_line('Nothing new was loaded for "&hkd_file".');
  end if;

  -- The upload hook queued its events in this transaction. The worker sees them at the commit.
  commit;
end;
/

-- The correct type of every sample file, for measuring the classifier in lesson 2.
merge into hkd_ai_labels t
using (
@@LABEL_ROWS@@
) s
on (t.file_name = s.file_name)
when matched then
  update set t.expected_type = s.expected_type, t.note = s.note
when not matched then
  insert (file_name, expected_type, note)
  values (s.file_name, s.expected_type, s.note);
commit;

set feedback on
"""

parts = [HEAD]
with open(HERE / "labels.csv") as f:
    names = [row["file_name"] for row in csv.DictReader(f)]
for name in names:
    b64 = base64.b64encode((PDFS / name).read_bytes()).decode()
    scope = f"'{name.upper()}'" if name.endswith("_v2.pdf") else f"'ALL', '{name.upper()}'"
    parts.append(f"\n  if upper('&hkd_file') in ({scope}) then\n    declare\n      l_b64 clob;\n    begin\n      sys.dbms_lob.createtemporary(l_b64, true);\n")
    for i in range(0, len(b64), CHUNK):
        parts.append(f"      sys.dbms_lob.append(l_b64, '{b64[i:i + CHUNK]}');\n")
    parts.append(f"      put('{name}', l_b64);\n    end;\n  end if;\n")
with open(HERE / "labels.csv") as f:
    rows = list(csv.DictReader(f))
label_rows = "\n  union all\n".join(
    "  select '{}' as file_name, '{}' as expected_type, '{}' as note from dual".format(
        r["file_name"], r["expected_type"], r["note"].replace("'", "''"))
    for r in rows)
parts.append(TAIL.replace("@@LABEL_ROWS@@", label_rows))
OUT.write_text("".join(parts))
print(f"{OUT.name}: {OUT.stat().st_size // 1024} KB, {len(names)} files")


