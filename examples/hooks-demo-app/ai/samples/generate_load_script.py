# ---------------------------------------------------------------------------------------------
# 03_new_version.sql: saves the amended contract as a new version of the first one
# ---------------------------------------------------------------------------------------------
VERSION_OUT = HERE.parent / "03_new_version.sql"
VERSION_PDF = "supply_agreement_ferrotek_v2.pdf"

VERSION = r"""-- Lesson 3: save an amended contract as a new version. GENERATED by
-- samples/generate_load_script.py. Run in SQLcl or SQL*Plus, connected as the ADM schema owner,
-- after lesson 2:
--
--   @03_new_version.sql
--
-- The new version fires the version hook, and the worker classifies it again. The script
-- waits for that, so it takes about 20 seconds and uses one model call.

-- @dblinter ignore(g-5010): a tutorial script prints its results with dbms_output on
-- purpose, so the reader sees them directly in SQLcl.

define hkd_user = ADMIN

set define on
set verify off
set serveroutput on
set feedback off
set linesize 200
column workflow_code format a20
column status format a8
column summary format a100
column version_number format 9999 heading "VER"
column verdict_status format a12
column doc_type format a10

-- ---------------------------------------------------------------------------
-- Save the amended contract as version 2
-- ---------------------------------------------------------------------------
declare
  l_b64        clob;
  l_doc_id     adm_documents.document_id%type;
  l_version_id adm_document_versions.version_id%type;
begin
  sys.dbms_lob.createtemporary(l_b64, true);
@@VERSION_CHUNKS@@
  adm_context_api.system_user_login('&hkd_user');
  select document_id
    into l_doc_id
    from adm_documents
   where document_name = 'supply_agreement_ferrotek.pdf'
     and deleted_flag  = 'N';

  -- p_allow_merge => false always adds a version. With the default, a save shortly after the
  -- previous one can replace that version instead (setting VERSION_MERGE_WINDOW_MINUTES).
  l_version_id := adm_document_api.add_document_version(
    p_document_id  => l_doc_id
  , p_file_content => apex_web_service.clobbase642blob(l_b64)
  , p_allow_merge  => false
  );
  sys.dbms_output.put_line('Saved version ' || l_version_id || ' of document ' || l_doc_id);

  -- The version hook queued its event in this transaction. The worker sees it at the commit.
  commit;
end;
/
@wait.sql

-- ---------------------------------------------------------------------------
-- What the worker did with the new version
-- ---------------------------------------------------------------------------
select w.workflow_code
     , w.status
     , w.summary
  from hkd_workflow_runs w
 where w.document_id in (select d.document_id from adm_documents d where d.document_name = 'supply_agreement_ferrotek.pdf' and d.deleted_flag = 'N')
   and w.hook_key = 'AFTER_NEW_FILE_VERSION'
 order by w.run_id;

-- The newest verdict is for the new version. The verdict of version 1 is still in the history.
select v.version_number
     , r.doc_type
     , r.status as verdict_status
     , r.created_at
  from hkd_ai_results r
  join adm_document_versions v
    on v.version_id = r.version_id
 where r.document_id = (select d.document_id from adm_documents d where d.document_name = 'supply_agreement_ferrotek.pdf' and d.deleted_flag = 'N')
 order by r.result_id;
"""
_b64v = base64.b64encode((PDFS / VERSION_PDF).read_bytes()).decode()
_chunksv = "".join(f"  sys.dbms_lob.append(l_b64, '{_b64v[i:i + CHUNK]}');\n" for i in range(0, len(_b64v), CHUNK))
VERSION_OUT.write_text(VERSION.replace("@@VERSION_CHUNKS@@\n", _chunksv))
print(f"{VERSION_OUT.name}: {VERSION_OUT.stat().st_size // 1024} KB")
