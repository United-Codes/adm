#!/usr/bin/env python3
"""Writes ../db/02_aic_load_pdfs.sql: loads the sample PDFs into ADM without any file access.

Every PDF becomes a base64 literal inside the script, so a reader needs SQLcl and nothing else.
Run it after generate_samples.py:

    python3 generate_load_script.py
"""
import base64
import csv
from pathlib import Path

HERE = Path(__file__).parent
PDFS = HERE / "pdf"
OUT = HERE.parent / "db" / "02_aic_load_pdfs.sql"
CHUNK = 1800  # characters per PL/SQL literal; far below the 32 KB literal limit

HEAD = """-- Step 2 of 7: loads the sample PDFs into the two group folders and shares some of them across.
-- Run as the ADM schema owner, after 01_aic_users.sql. GENERATED by samples/generate_load_script.py:
-- change the PDFs there, not here. Re-runnable: a file that is already there is left alone.
--
--   contracts -> /groups/aic_legal   (the Legal group sees them all)
--   policies  -> /groups/aic_hr      (the HR group sees them all)
--
-- Then each file is shared with the OTHER group when the manifest says so. The Helios contract
-- (Legal only) and the salary bands (HR only) are not shared. That is the whole access model:
-- AIC_LEGAL sees 5 contracts and 4 policies, AIC_HR sees 4 contracts and 5 policies.
--
-- EVERY upload here passes p_run_hooks => false. Only an administrator or the system user may do
-- that. It keeps any hook that is registered in this schema (a classifier, a virus scan, a
-- workflow) from running on demo files. Nothing is classified, tagged or sent to a model.
--
-- The scanned amendment gets the annotation aic.scan = Y. The contracts collection reads it to
-- send only that file to a model for text extraction (see 03_aic_collections.sql).
--
-- Every company, person and number in the PDFs is invented.

-- @dblinter ignore(g-5010): a tutorial script prints its results with dbms_output on
-- purpose, so the reader sees them directly in SQLcl.

set define off
set serveroutput on
set feedback off

declare
  l_legal_folder adm_folders.folder_id%type;
  l_hr_folder    adm_folders.folder_id%type;
  l_legal_group  adm_groups.group_id%type;
  l_hr_group     adm_groups.group_id%type;
  l_loaded       pls_integer := 0;

  procedure put (
    p_name        in varchar2
  , p_folder_id   in adm_folders.folder_id%type
  , p_share_group in adm_groups.group_id%type
  , p_scanned     in varchar2
  , p_b64         in clob
  )
  as
    l_doc_id adm_documents.document_id%type;
  begin
    select min(document_id)
      into l_doc_id
      from adm_documents
     where folder_id     = p_folder_id
       and document_name = p_name
       and deleted_flag  = 'N';

    if l_doc_id is not null then
      sys.dbms_output.put_line('  already there: ' || p_name);
      return;
    end if;

    l_doc_id := adm_document_api.create_document(
      p_folder_id      => p_folder_id
    , p_document_name  => p_name
    , p_file_content   => apex_web_service.clobbase642blob(p_b64)
    , p_file_mime_type => 'application/pdf'
    , p_run_hooks      => false
    );
    l_loaded := l_loaded + 1; -- @dblinter ignore(g-7130): put is a helper of this one block, and the counter is the state of the block

    if p_scanned = 'Y' then
      adm_annotations_api.add_document_annotation(l_doc_id, 'aic.scan', 'Y');
    end if;

    if p_share_group is not null then
      adm_shares_api.share_document(
        p_document_id => l_doc_id
      , p_user_ids    => null
      , p_groups_ids  => to_char(p_share_group)
      , p_share_role  => adm_access_control_api.c_view
      );
    end if;

    sys.dbms_output.put_line('  loaded: ' || p_name || ' (document ' || l_doc_id || ')'
      || case when p_share_group is not null then ', shared with the other group' end);
  end put;
begin
  adm_context_api.system_login;

  l_legal_folder := adm_folder_api.get_folder_id('/groups/aic_legal');
  l_hr_folder    := adm_folder_api.get_folder_id('/groups/aic_hr');
  select group_id into l_legal_group from adm_groups where group_name = 'AIC_LEGAL';
  select group_id into l_hr_group    from adm_groups where group_name = 'AIC_HR';
"""

TAIL = """
  commit;
  sys.dbms_output.put_line(l_loaded || ' file(s) loaded.');
end;
/
set feedback on
"""

parts = [HEAD]
with open(HERE / "manifest.csv") as f:
    rows = list(csv.DictReader(f))
for r in rows:
    name = r["file_name"]
    folder = "l_legal_folder" if r["corpus"] == "contracts" else "l_hr_folder"
    # shared with the other group when that group may see it
    if r["corpus"] == "contracts":
        share = "l_hr_group" if r["hr"] == "Y" else "null"
    else:
        share = "l_legal_group" if r["legal"] == "Y" else "null"
    b64 = base64.b64encode((PDFS / name).read_bytes()).decode()
    parts.append(f"\n  declare\n    l_b64 clob;\n  begin\n    sys.dbms_lob.createtemporary(l_b64, true);\n")
    for i in range(0, len(b64), CHUNK):
        parts.append(f"    sys.dbms_lob.append(l_b64, '{b64[i:i + CHUNK]}');\n")
    parts.append(f"    put('{name}', {folder}, {share}, '{r['scanned']}', l_b64);\n  end;\n")
parts.append(TAIL)
OUT.write_text("".join(parts))
print(f"{OUT.name}: {OUT.stat().st_size // 1024} KB, {len(rows)} files")
