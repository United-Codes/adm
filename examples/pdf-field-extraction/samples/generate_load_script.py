#!/usr/bin/env python3
"""Writes three scripts of the course from the sample files, so that a reader needs SQLcl and nothing else:

- ../00_load_samples.sql loads the files of pdf/ into ADM. Every file is a base64 literal in the script.
- ../05_upload_inbox.sql uploads the files of inbox/ the same way.
- ../02_seed_test_set.sql writes the correct values of pdf/expected.json into the test set of the
  profile pfx_supplier_forms, with adm_ai_form_extract_api.set_expected.

Run it after make_invoices.py, make_forms.py and make_scans.py:

    python3 generate_load_script.py
"""
import base64
import json
from pathlib import Path

HERE = Path(__file__).parent
FILES = HERE / "pdf"
INBOX = HERE / "inbox"
CHUNK = 1800  # characters per PL/SQL literal; far below the 32 KB literal limit

HEAD = """-- {title}
-- Run in SQLcl or SQL*Plus, connected as the ADM schema owner, from the course folder.
-- GENERATED by samples/generate_load_script.py: change the samples there, not here.
--
-- The files go into the folder {folder} in the home folder of the ADM user of settings.sql, as that
-- user. A file that is already there is left alone. The script does not run upload hooks.
--
-- Every company, person, IBAN and number in the files is invented.

-- @dblinter ignore(g-5010): a tutorial script prints its results with dbms_output on
-- purpose, so the reader sees them directly in SQLcl.

@@settings.sql

set define on
set verify off
set serveroutput on
set feedback off

declare
  l_folder_id   adm_folders.folder_id%type;
  l_loaded      pls_integer := 0;

  procedure put (
    p_name in varchar2
  , p_mime in varchar2
  , p_b64  in clob
  )
  as
    l_doc_id adm_documents.document_id%type;
  begin
    select max(d.document_id)
      into l_doc_id
      from adm_documents d
     where d.folder_id     = l_folder_id -- @dblinter ignore(g-7130): put is a helper of this one block, and the folder is the state of the block
       and d.document_name = p_name
       and d.deleted_flag  = 'N';

    if l_doc_id is not null then
      sys.dbms_output.put_line('  already there: ' || p_name);
      return;
    end if;

    l_doc_id := adm_document_api.create_document(
      p_folder_id      => l_folder_id -- @dblinter ignore(g-7130): put is a helper of this one block, and the folder is the state of the block
    , p_document_name  => p_name
    , p_file_content   => apex_web_service.clobbase642blob(p_b64)
    , p_file_mime_type => p_mime
    , p_run_hooks      => false
    );
    l_loaded := l_loaded + 1; -- @dblinter ignore(g-7130): put is a helper of this one block, and the counter is the state of the block
    sys.dbms_output.put_line('  loaded: ' || p_name);
  end put;

begin
  adm_context_api.system_user_login('&pfx_user');

  begin
    l_folder_id := adm_folder_api.get_folder_id('&pfx_home/{folder}');
  exception
    when adm_error.e_folder_not_found then
      l_folder_id := adm_folder_api.add_folder('{folder}', adm_folder_api.get_folder_id('&pfx_home'));
  end;
"""

TAIL = """
  commit;
  sys.dbms_output.put_line('{done}: ' || l_loaded || ' new file(s) in &pfx_home/{folder}');
end;
/
"""

SEED_HEAD = """-- Lessons 2 and 3: writes the correct values of every sample document into the test set of the
-- profile pfx_supplier_forms, with adm_ai_form_extract_api.set_expected. measure compares its
-- results with them. Run in SQLcl or SQL*Plus, connected as the ADM schema owner, after
-- 00_load_samples.sql. GENERATED by samples/generate_load_script.py from
-- samples/pdf/expected.json: change the values there, not here.
--
-- A test case names the form of its document, so a document whose form does not exist yet is
-- skipped. Lesson 3 runs the script again after it adds the forms. Running it again replaces the
-- test cases of the samples. Calls no model.

-- @dblinter ignore(g-5010): a tutorial script prints its results with dbms_output on
-- purpose, so the reader sees them directly in SQLcl.

@@settings.sql

set define on
set verify off
set serveroutput on
set feedback off

declare
  l_profile_id number;
  l_written    pls_integer := 0;
  l_skipped    pls_integer := 0;

  procedure expect (
    p_document_name in varchar2
  , p_expected      in clob
  )
  as
    l_expected    json_object_t;
    l_document_id adm_documents.document_id%type;
  begin
    l_expected := json_object_t(p_expected);
    select document_id
      into l_document_id
      from adm_my_documents_v
     where folder_path = '&pfx_home/pfx_samples'
       and document_name = p_document_name;

    -- No form_code: the document is no form, and its extraction must go to review.
    adm_ai_form_extract_api.set_expected(
      p_profile_id  => l_profile_id -- @dblinter ignore(g-7130): expect is a helper of this one block, and the profile is the state of the block
    , p_document_id => l_document_id
    , p_form_code   => l_expected.get_string('form_code')
    , p_fields      => case when l_expected.get_object('fields') is not null then l_expected.get_object('fields').to_clob end
    , p_line_items  => case when l_expected.get_array('line_items') is not null then l_expected.get_array('line_items').to_clob end
    );
    l_written := l_written + 1; -- @dblinter ignore(g-7130): expect is a helper of this one block, and the counter is the state of the block
  exception
    when adm_ai_error.e_form_not_found then
      l_skipped := l_skipped + 1; -- @dblinter ignore(g-7130): expect is a helper of this one block, and the counter is the state of the block
  end expect;

begin
  adm_context_api.system_user_login('&pfx_user');
  l_profile_id := adm_ai_form_config_api.get_profile_id('pfx_supplier_forms');
"""

SEED_TAIL = """
  commit;
  sys.dbms_output.put_line('test set: ' || l_written || ' document(s) written');
  if l_skipped > 0 then
    sys.dbms_output.put_line('skipped, because the form does not exist yet: ' || l_skipped || ' document(s)');
  end if;
end;
/
"""


def literal_block(b64: str) -> str:
    return "\n".join(f"      sys.dbms_lob.append(l_b64, '{b64[i:i + CHUNK]}');" for i in range(0, len(b64), CHUNK))


def sample_files(files: Path):
    return sorted(p for p in files.iterdir() if p.suffix in (".pdf", ".png"))


def write_load(out: Path, files: Path, folder: str, title: str, done: str):
    parts = [HEAD.format(title=title, folder=folder)]
    for f in sample_files(files):
        mime = "application/pdf" if f.suffix == ".pdf" else "image/png"
        b64 = base64.b64encode(f.read_bytes()).decode()
        parts.append(f"""
  declare
    l_b64 clob;
  begin
    sys.dbms_lob.createtemporary(l_b64, true);
{literal_block(b64)}
    put('{f.name}', '{mime}', l_b64);
  end;
""")
    parts.append(TAIL.format(done=done, folder=folder))
    out.write_text("".join(parts))
    print(f"wrote {out}")


def write_seed(out: Path, files: Path, expected):
    parts = [SEED_HEAD]
    for f in sample_files(files):
        # "&" starts a substitution variable in SQLcl, so it goes in as chr(38).
        exp = json.dumps(expected[f.stem], ensure_ascii=False).replace("&", "~' || chr(38) || q'~")
        parts.append(f"  expect('{f.name}', q'~{exp}~');\n")
    parts.append(SEED_TAIL)
    out.write_text("".join(parts))
    print(f"wrote {out}")


def main():
    write_load(HERE.parent / "00_load_samples.sql", FILES, "pfx_samples",
               'Loads the sample documents of the course "Extract data from PDF forms with a local model" into ADM.',
               "samples loaded")
    write_load(HERE.parent / "05_upload_inbox.sql", INBOX, "pfx_inbox",
               "Lesson 5: uploads four new documents into the inbox folder, the way an application would.",
               "inbox")
    write_seed(HERE.parent / "02_seed_test_set.sql", FILES, json.loads((FILES / "expected.json").read_text()))


if __name__ == "__main__":
    main()
